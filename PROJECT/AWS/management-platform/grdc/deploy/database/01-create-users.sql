SET ECHO OFF
SET VERIFY OFF
SET SERVEROUTPUT ON
SET DEFINE ON
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
ACCEPT GRDC_A_PASSWORD CHAR PROMPT 'MP_GRDCA password (24-30 alphanumeric characters): ' HIDE
ACCEPT GRDC_B_PASSWORD CHAR PROMPT 'MP_GRDCB password (24-30 alphanumeric characters): ' HIDE
DECLARE
PROCEDURE validate_password(p VARCHAR2) IS
BEGIN
    IF p IS NULL OR LENGTHB(p) NOT BETWEEN 24 AND 30
       OR NOT REGEXP_LIKE(p, '^[A-Za-z0-9]+$', 'c') THEN
      RAISE_APPLICATION_ERROR(-20001, 'Expected 24-30 ASCII alphanumeric password');
END IF;
END;
  PROCEDURE ensure_user(u VARCHAR2, p VARCHAR2) IS
    n NUMBER;
BEGIN
SELECT COUNT(*) INTO n FROM all_users WHERE username = u;
IF n = 0 THEN
      EXECUTE IMMEDIATE 'CREATE USER ' || u || ' IDENTIFIED BY "' || p ||
        '" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
      DBMS_OUTPUT.PUT_LINE(u || ': created');
ELSE
      DBMS_OUTPUT.PUT_LINE(u || ': already exists; password unchanged');
END IF;
EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE TRIGGER TO ' || u;
END;
BEGIN
  validate_password('&GRDC_A_PASSWORD');
  validate_password('&GRDC_B_PASSWORD');
  ensure_user('MP_GRDCA', '&GRDC_A_PASSWORD');
  ensure_user('MP_GRDCB', '&GRDC_B_PASSWORD');
END;
/
UNDEFINE GRDC_A_PASSWORD
UNDEFINE GRDC_B_PASSWORD
